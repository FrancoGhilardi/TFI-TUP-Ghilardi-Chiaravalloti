import { Entity } from "../../../../shared/domain/entity.js";
import type { Money } from "../../../../shared/domain/value-objects/money.js";
import type { Slug } from "../../../../shared/domain/value-objects/slug.js";
import {
  PRODUCT_DESCRIPTION_MAX_LENGTH,
  PRODUCT_TITLE_MAX_LENGTH,
  STOCK_MAX,
} from "../catalog-limits.js";
import { InvalidNewUntilError } from "../errors/invalid-new-until-error.js";
import { InvalidPriceError } from "../errors/invalid-price-error.js";
import { InvalidProductTitleError } from "../errors/invalid-product-title-error.js";
import { InvalidSaleEndError } from "../errors/invalid-sale-end-error.js";
import { InvalidStockError } from "../errors/invalid-stock-error.js";
import { ProductDeletedError } from "../errors/product-deleted-error.js";
import { ProductNotDeletedError } from "../errors/product-not-deleted-error.js";
import { ProductWithoutCategoryError } from "../errors/product-without-category-error.js";
import { SalePriceNotLowerError } from "../errors/sale-price-not-lower-error.js";
import { SelfRelatedProductError } from "../errors/self-related-product-error.js";
import { optionalDescription, requiredText, sortOrder } from "../text.js";
import { CategoryAssignment } from "../value-objects/category-assignment.js";
import type { Sku } from "../value-objects/sku.js";

export interface ProductProps {
  id: string;
  /** Generated by the database once; it never changes. */
  sku: Sku;
  title: string;
  /** Generated once from the title; it never changes. */
  slug: Slug;
  description?: string;
  price: Money;
  salePrice?: Money;
  onSale: boolean;
  saleEndsAt?: Date;
  stock: number;
  featured: boolean;
  isNewFlag: boolean;
  newUntil?: Date;
  sortOrder: number;
  active: boolean;
  categories: CategoryAssignment[];
  relatedProductIds: string[];
  createdBy?: string;
  updatedBy?: string;
  createdAt: Date;
  updatedAt: Date;
  deletedAt?: Date;
}

export interface NewProductProps {
  id: string;
  sku: Sku;
  title: string;
  slug: Slug;
  description?: string;
  price: Money;
  stock?: number;
  sortOrder?: number;
  categories: CategoryAssignment[];
  createdBy: string;
  now: Date;
}

const checkedTitle = (title: string) =>
  requiredText(title, PRODUCT_TITLE_MAX_LENGTH, () => new InvalidProductTitleError());

const checkedDescription = (description: string | undefined) =>
  optionalDescription(description, PRODUCT_DESCRIPTION_MAX_LENGTH);

function checkedPrice(price: Money): Money {
  if (!price.isPositive()) {
    throw new InvalidPriceError();
  }
  return price;
}

function checkedStock(quantity: number): number {
  if (!Number.isInteger(quantity) || quantity < 0 || quantity > STOCK_MAX) {
    throw new InvalidStockError();
  }
  return quantity;
}

/**
 * A product for sale. A sale and the "new" mark count only until they end: past that date
 * they stop applying even though the flags are still stored. A deleted product can only be
 * restored, and its active state is kept across the deletion.
 */
export class Product extends Entity {
  private constructor(private readonly props: ProductProps) {
    super(props.id);
  }

  /** A new product is active, not on sale, not featured nor new; those are set afterwards. */
  static create(input: NewProductProps): Product {
    return new Product({
      id: input.id,
      sku: input.sku,
      title: checkedTitle(input.title),
      slug: input.slug,
      description: checkedDescription(input.description),
      price: checkedPrice(input.price),
      onSale: false,
      stock: checkedStock(input.stock ?? 0),
      featured: false,
      isNewFlag: false,
      sortOrder: sortOrder(input.sortOrder ?? 0),
      active: true,
      categories: CategoryAssignment.checked(input.categories),
      relatedProductIds: [],
      createdBy: input.createdBy,
      updatedBy: input.createdBy,
      createdAt: input.now,
      updatedAt: input.now,
    });
  }

  static reconstitute(props: ProductProps): Product {
    return new Product({
      ...props,
      categories: [...props.categories],
      relatedProductIds: [...props.relatedProductIds],
    });
  }

  get sku(): Sku {
    return this.props.sku;
  }

  get title(): string {
    return this.props.title;
  }

  get slug(): Slug {
    return this.props.slug;
  }

  get description(): string | undefined {
    return this.props.description;
  }

  get price(): Money {
    return this.props.price;
  }

  get salePrice(): Money | undefined {
    return this.props.salePrice;
  }

  get onSale(): boolean {
    return this.props.onSale;
  }

  get saleEndsAt(): Date | undefined {
    return this.props.saleEndsAt;
  }

  get stock(): number {
    return this.props.stock;
  }

  get featured(): boolean {
    return this.props.featured;
  }

  get isNewFlag(): boolean {
    return this.props.isNewFlag;
  }

  get newUntil(): Date | undefined {
    return this.props.newUntil;
  }

  get sortOrder(): number {
    return this.props.sortOrder;
  }

  get active(): boolean {
    return this.props.active;
  }

  get categories(): readonly CategoryAssignment[] {
    return this.props.categories;
  }

  get relatedProductIds(): readonly string[] {
    return this.props.relatedProductIds;
  }

  get createdBy(): string | undefined {
    return this.props.createdBy;
  }

  get updatedBy(): string | undefined {
    return this.props.updatedBy;
  }

  get createdAt(): Date {
    return this.props.createdAt;
  }

  get updatedAt(): Date {
    return this.props.updatedAt;
  }

  get deletedAt(): Date | undefined {
    return this.props.deletedAt;
  }

  isDeleted(): boolean {
    return this.props.deletedAt !== undefined;
  }

  /** Shown in the store: active and not deleted. */
  isVisible(): boolean {
    return this.props.active && !this.isDeleted();
  }

  /** On sale, with a sale price, and before the end of the sale if it has one. */
  isSaleActive(now: Date): boolean {
    return (
      this.props.onSale &&
      this.props.salePrice !== undefined &&
      (this.props.saleEndsAt === undefined || now.getTime() < this.props.saleEndsAt.getTime())
    );
  }

  /** Marked as new, and before the end of the mark if it has one. */
  isNewActive(now: Date): boolean {
    return (
      this.props.isNewFlag &&
      (this.props.newUntil === undefined || now.getTime() < this.props.newUntil.getTime())
    );
  }

  getPrimaryCategoryId(): string {
    const primary = this.props.categories.find((assignment) => assignment.isPrimary);
    // Every change checks it; only stored data broken outside the application lacks one.
    if (!primary) {
      throw new Error(`Product ${this.id} has no primary category`);
    }
    return primary.categoryId;
  }

  changeTitle(title: string): void {
    this.assertNotDeleted();
    this.props.title = checkedTitle(title);
  }

  changeDescription(description?: string): void {
    this.assertNotDeleted();
    this.props.description = checkedDescription(description);
  }

  /**
   * A sale still running must stay below the new price. One that already ended is dropped,
   * so a stale sale price never blocks a change of price. Changes record no author: the use
   * case compares before and after and calls `markUpdatedBy` only when something changed.
   */
  changePrice(price: Money, now: Date): void {
    this.assertNotDeleted();
    const checked = checkedPrice(price);
    // The same price changes nothing, not even a sale that already ended.
    if (checked.equals(this.props.price)) {
      return;
    }
    if (this.isSaleActive(now)) {
      if (!this.props.salePrice!.isLessThan(checked)) {
        throw new SalePriceNotLowerError();
      }
    } else {
      this.clearSale();
    }
    this.props.price = checked;
  }

  /** `endsAt`, if given, must be in the future; without it the sale runs until ended. */
  startSale(salePrice: Money, endsAt: Date | undefined, now: Date): void {
    this.assertNotDeleted();
    if (!salePrice.isPositive() || !salePrice.isLessThan(this.props.price)) {
      throw new SalePriceNotLowerError();
    }
    if (endsAt !== undefined && endsAt.getTime() <= now.getTime()) {
      throw new InvalidSaleEndError();
    }
    this.props.onSale = true;
    this.props.salePrice = salePrice;
    this.props.saleEndsAt = endsAt;
  }

  endSale(): void {
    this.assertNotDeleted();
    this.clearSale();
  }

  setStock(quantity: number): void {
    this.assertNotDeleted();
    this.props.stock = checkedStock(quantity);
  }

  setFeatured(featured: boolean): void {
    this.assertNotDeleted();
    this.props.featured = featured;
  }

  /** `until`, if given, must be in the future; without it the mark stays until removed. */
  markAsNew(until: Date | undefined, now: Date): void {
    this.assertNotDeleted();
    if (until !== undefined && until.getTime() <= now.getTime()) {
      throw new InvalidNewUntilError();
    }
    this.props.isNewFlag = true;
    this.props.newUntil = until;
  }

  unmarkAsNew(): void {
    this.assertNotDeleted();
    this.props.isNewFlag = false;
    this.props.newUntil = undefined;
  }

  changeSortOrder(order: number): void {
    this.assertNotDeleted();
    this.props.sortOrder = sortOrder(order);
  }

  /** The caller checks the categories exist and are visible. */
  assignCategories(assignments: CategoryAssignment[]): void {
    this.assertNotDeleted();
    this.props.categories = CategoryAssignment.checked(assignments);
  }

  /** Repeated ids are dropped; the caller checks the products exist. */
  setRelatedProducts(productIds: string[]): void {
    this.assertNotDeleted();
    if (productIds.includes(this.id)) {
      throw new SelfRelatedProductError();
    }
    this.props.relatedProductIds = [...new Set(productIds)];
  }

  activate(): void {
    this.assertNotDeleted();
    this.props.active = true;
  }

  deactivate(): void {
    this.assertNotDeleted();
    this.props.active = false;
  }

  /** Records who made the changes being saved; the database stamps the time. */
  markUpdatedBy(actorId: string): void {
    this.props.updatedBy = actorId;
  }

  /** Deletion is always logical and keeps the active state, which a restore brings back. */
  softDelete(actorId: string, now: Date): void {
    if (this.isDeleted()) {
      return;
    }
    this.props.deletedAt = now;
    this.props.updatedBy = actorId;
  }

  /**
   * `hasCurrentCategory`: whether any of its categories is not deleted. A deleted product
   * cannot be edited, so one whose categories are all gone waits for one of them to return.
   */
  restore(actorId: string, hasCurrentCategory: boolean): void {
    if (!this.isDeleted()) {
      throw new ProductNotDeletedError();
    }
    if (!hasCurrentCategory) {
      throw new ProductWithoutCategoryError();
    }
    this.props.deletedAt = undefined;
    this.props.updatedBy = actorId;
  }

  private clearSale(): void {
    this.props.onSale = false;
    this.props.salePrice = undefined;
    this.props.saleEndsAt = undefined;
  }

  private assertNotDeleted(): void {
    if (this.isDeleted()) {
      throw new ProductDeletedError();
    }
  }
}
